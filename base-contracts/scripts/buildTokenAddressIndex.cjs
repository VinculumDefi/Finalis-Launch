// Builds deployment/tokenAddressIndex.json: for every EVM token row of the 961
// written registry rows, (environment, token address) -> that row's
// canonicalAssetId, using the address already on the row ("identifier").
// No rows are added.
//
// Duplicate rule (52 addresses sit on two or more rows of the SAME environment;
// an address on one chain is one contract):
//   1. Only rows whose environment is the lock's chain are candidates (the
//      index key includes the environment, so the same address on two chains
//      maps independently).
//   2. Pick the row whose symbol equals the contract's own on-chain symbol()
//      exactly; else equal ignoring case.
//   3. Else the lowest row number (the first listing; later rows are aliases
//      such as USDC_ETH).
// Every candidate must have the same decimals, or the build fails.
// symbol() values come from deployment/tokenSymbolsSnapshot.json.
const fs = require("fs");
const path = require("path");
const DEP = path.join(__dirname, "..", "deployment");
const EVM = ["Ethereum", "Arbitrum", "Optimism", "Polygon", "BNB Smart Chain", "Avalanche", "Base"];

function buildTokenAddressIndex() {
  const reg = JSON.parse(fs.readFileSync(path.join(DEP, "assetRegistry.resolved.json"), "utf8"));
  const snap = JSON.parse(fs.readFileSync(path.join(DEP, "tokenSymbolsSnapshot.json"), "utf8")).symbols;
  const written = reg.entries.filter((e) => e.decimals != null && e.sameKeyAsRow == null);
  const groups = new Map();
  for (const e of written) {
    if (!EVM.includes(e.environmentId)) continue;
    if (!/^0x[0-9a-fA-F]{40}$/.test(e.identifier || "") || /^0x0{40}$/.test(e.identifier)) continue; // natives
    const k = e.environmentId + "|" + e.identifier.toLowerCase();
    if (!groups.has(k)) groups.set(k, []);
    groups.get(k).push(e);
  }
  const entries = [], duplicates = [];
  for (const [k, rows] of groups) {
    rows.sort((a, b) => a.row - b.row);
    let pick = rows[0], why = "single row";
    if (rows.length > 1) {
      if (new Set(rows.map((r) => r.decimals)).size !== 1) throw new Error("decimals differ for " + k);
      const sym = snap[k];
      if (sym == null) throw new Error("no symbol() snapshot for duplicate " + k);
      const exact = rows.find((r) => r.symbol === sym);
      const loose = rows.find((r) => r.symbol.toUpperCase() === String(sym).toUpperCase());
      pick = exact || loose || rows[0];
      why = exact ? "symbol() exact match" : loose ? "symbol() case-insensitive match" : "lowest row (no symbol match)";
      duplicates.push({ environmentId: rows[0].environmentId, address: rows[0].identifier, contractSymbol: sym,
        rows: rows.map((r) => ({ row: r.row, symbol: r.symbol })), chosenRow: pick.row, rule: why });
    }
    entries.push({ environmentId: pick.environmentId, token: pick.identifier, canonicalAssetId: pick.canonicalAssetId, row: pick.row, symbol: pick.symbol });
  }
  entries.sort((a, b) => a.row - b.row);
  return { entries, duplicates };
}

module.exports = { buildTokenAddressIndex };

if (require.main === module) {
  const r = buildTokenAddressIndex();
  fs.writeFileSync(path.join(DEP, "tokenAddressIndex.json"), JSON.stringify({
    _note: "Generated by scripts/buildTokenAddressIndex.cjs from assetRegistry.resolved.json. (environment, token address) -> registry row. No rows added. Duplicate rule in the script header.",
    count: r.entries.length, duplicateCount: r.duplicates.length, entries: r.entries, duplicates: r.duplicates }, null, 1) + "\n");
  console.log(r.entries.length, "indexed addresses;", r.duplicates.length, "duplicate addresses resolved");
  for (const d of r.duplicates) if (d.rule !== "symbol() exact match") console.log(" ", d.environmentId, d.address.slice(0, 6) + "…", d.rows.map((x) => x.row + ":" + x.symbol).join(" "), "->", d.chosenRow, d.rule);
}
