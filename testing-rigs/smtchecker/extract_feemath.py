#!/usr/bin/env python3
"""Build harness/FeeMath.sol from verbatim copies of the Base CVL fee math
(_quote and its constants) and the Verifier fee check expression.

Inheriting the whole BaseCommitmentVaultLock made the CHC engine run out of
memory on the shared box (first harness_feemath attempts, exit 247). This
copies the exact source text of the pure function under test instead.
"""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
CVL = os.path.join(HERE, "..", "..", "base-contracts", "contracts", "BaseCommitmentVaultLock.sol")
VER = os.path.join(HERE, "..", "..", "base-contracts", "contracts", "VinculumFinalisVerifier.sol")
lines = open(CVL).read().split("\n")
vlines = open(VER).read().split("\n")


def func(name):
    start = next(i for i, l in enumerate(lines) if re.search(r"function %s\(" % name, l))
    depth, i = 0, start
    while True:
        depth += lines[i].count("{") - lines[i].count("}")
        if depth == 0 and "{" in "".join(lines[start:i + 1]):
            return start, i
        i += 1


CONSTS = ["STANDARD_FEE_BPS", "BPS_DENOMINATOR", "HANDSHAKE_DURATION", "HANDSHAKE_USD_MIN",
          "HANDSHAKE_USD_MAX", "STANDARD_USD_MIN"]
# The Verifier fee check (VF-COM-011), copied as text; it must match in both places.
vi = [i for i, l in enumerate(vlines) if "VF-COM-011: fee != floor" in l]
vexpr = re.search(r"require\((fee == \(gross \* STANDARD_FEE_BPS\) / 10000)", vlines[vi[0]]).group(1)
assert all(vexpr in vlines[i] for i in vi), "Verifier fee checks differ"

out = ["// SPDX-License-Identifier: MIT", "pragma solidity 0.8.19;", "",
       "// GENERATED by extract_feemath.py from base-contracts/contracts/BaseCommitmentVaultLock.sol",
       "// and VinculumFinalisVerifier.sol. _quote and the constants are verbatim copies;",
       "// only the prop_ function is new.",
       'import "../../../base-contracts/contracts/CommitmentDurations.sol";', "", "contract FeeMath {"]
for c in CONSTS:
    i = next(i for i, l in enumerate(lines) if re.search(r"constant %s\s*=" % c, l))
    out.append("    // copied from BaseCommitmentVaultLock.sol line %d" % (i + 1))
    out.append(lines[i])
a, b = func("_quote")
out.append("    // copied from BaseCommitmentVaultLock.sol lines %d-%d" % (a + 1, b + 1))
out.extend(lines[a:b + 1])
out.append('''
    // F1: fee plus principal always equals gross (no value created or lost).
    // F2: fee is exactly floor(gross / 20).
    // F3: the Verifier check (VinculumFinalisVerifier.sol lines %s) accepts the CVL fee.
    // F4: principal is never zero for gross >= 2.
    // F5: the duration multiplier is between 1.0x and 8.0x.
    function prop_quote(uint256 gross, uint256 duration, uint256 usd) public pure {
        (uint256 fee, uint256 principal, uint256 m) = _quote(gross, duration, usd);
        assert(fee + principal == gross);
        assert(fee == gross / 20);
        assert(%s);
        if (gross >= 2) assert(principal > 0);
        assert(m >= 10000 && m <= 80000);
    }
}''' % (", ".join(str(i + 1) for i in vi), vexpr))
open(os.path.join(HERE, "harness", "FeeMath.sol"), "w").write("\n".join(out) + "\n")
print("FeeMath.sol: _quote lines %d-%d, Verifier fee check lines %s" % (a + 1, b + 1, [i + 1 for i in vi]))
