#!/usr/bin/env python3
"""Build harness/IssuanceMath.sol from verbatim copies of the Verifier's
issuance functions and constants.

Inheriting the whole Verifier made the CHC engine run out of memory (see
results/runlog.txt, first harness_issuance attempt). This script copies the
exact source text of the pure functions under test, so the harness checks the
production code, and records the copied line ranges in the header.
"""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "base-contracts", "contracts", "VinculumFinalisVerifier.sol")
text = open(SRC).read()
lines = text.split("\n")

def func(name):
    start = next(i for i, l in enumerate(lines) if re.search(r"function %s\(" % name, l))
    depth, i = 0, start
    while True:
        depth += lines[i].count("{") - lines[i].count("}")
        if depth == 0 and "{" in "".join(lines[start:i + 1]):
            return start, i
        i += 1

CONSTS = ["SCALE", "DECAY_SURVIVAL_FP", "DECAY_PERIOD_DAYS", "VCLM_INITIAL_RATE", "VCLM_FLOOR_RATE",
          "CHONX_INITIAL_RATE", "CHONX_FLOOR_RATE", "S1_MULTIPLIER_BPS", "S2_MULTIPLIER_BPS", "S3_MULTIPLIER_BPS"]
out = ["// SPDX-License-Identifier: MIT", "pragma solidity 0.8.19;", "",
       "// GENERATED by extract_issuance.py from base-contracts/contracts/VinculumFinalisVerifier.sol.",
       "// Function bodies and constants are verbatim copies; only the prop_ functions are new.",
       'import "../../../base-contracts/contracts/CommitmentDurations.sol";', "", "contract IssuanceMath {"]
for c in CONSTS:
    i = next(i for i, l in enumerate(lines) if re.search(r"constant %s\s*=" % c, l))
    out.append("    // copied from line %d" % (i + 1))
    out.append(lines[i])
for f in ["_computeIssuance", "_computeEmissionRate", "_getDurationMultiplierBps"]:
    a, b = func(f)
    out.append("    // copied from lines %d-%d" % (a + 1, b + 1))
    out.extend(lines[a:b + 1])
out.append('''
    // I1: issuance is monotonic in verified USD (more value never mints less).
    function prop_monotonicUsd(uint256 u1, uint256 u2, uint8 out, uint8 cls, uint256 dur) public pure {
        require(u1 <= u2);
        require(u2 <= 1e36);
        assert(_computeIssuance(u1, out, cls, dur, 0) <= _computeIssuance(u2, out, cls, dur, 0));
    }

    // I2: issuance never exceeds usd * initialRate * 12 (1.5x custody times 8.0x duration).
    function prop_upperBound(uint256 usd, uint8 out, uint8 cls, uint256 dur) public pure {
        require(usd <= 1e36);
        uint256 rate = out == 0 ? VCLM_INITIAL_RATE : CHONX_INITIAL_RATE;
        assert(_computeIssuance(usd, out, cls, dur, 0) <= (usd * rate / SCALE) * 12);
    }

    // I3: the emission rate stays between floor and initial rate (bounded days).
    function prop_rateBounds(uint8 out, uint256 daysSince) public pure {
        require(daysSince <= 120);
        uint256 r = _computeEmissionRate(out, daysSince);
        uint256 init = out == 0 ? VCLM_INITIAL_RATE : CHONX_INITIAL_RATE;
        uint256 flo = out == 0 ? VCLM_FLOOR_RATE : CHONX_FLOOR_RATE;
        assert(r >= flo && r <= init);
    }

    // I4: day 0 always gives the highest rate. This is what makes a
    // caller-chosen valuationTimestamp (STATIC-H02) profitable.
    function prop_dayZeroIsMax(uint8 out, uint256 daysSince) public pure {
        require(daysSince <= 120);
        assert(_computeEmissionRate(out, 0) >= _computeEmissionRate(out, daysSince));
    }
}''')
open(os.path.join(HERE, "harness", "IssuanceMath.sol"), "w").write("\n".join(out) + "\n")
print("wrote harness/IssuanceMath.sol")
